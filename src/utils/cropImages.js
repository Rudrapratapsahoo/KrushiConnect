// Ultimate fallback - a generic agriculture/farming image
export const defaultFallbackImage = 'https://images.unsplash.com/photo-1500595046743-cd271d694d30?w=800&q=80';

/**
 * Auto-detects the best image for a crop based on name and category.
 * Uses fuzzy matching: tries exact match first, then partial match, then category fallback.
 * @param {string} name - Name of the crop
 * @param {string} category - Category of the crop
 * @returns {string} Image URL
 */
export const getDetectedImageUrl = (name, category) => {
  if (!name) return categoryImages[category] || defaultFallbackImage;
  
  const normalizedName = name.toLowerCase().trim();
  
  // 1. Try exact match first
  if (cropImages[normalizedName]) {
    return cropImages[normalizedName];
  }

  // 2. Try matching multi-word crop name keys (e.g., "basmati rice" matches "basmati rice")
  for (const [key, url] of Object.entries(cropImages)) {
    if (key.length > 3 && normalizedName === key) {
      return url;
    }
  }

  // 3. Try partial match — check if any keyword is contained in the product name
  //    Sort keys by length (longest first) so more specific names match before generic ones
  const sortedKeys = Object.keys(cropImages).sort((a, b) => b.length - a.length);
  for (const key of sortedKeys) {
    if (normalizedName.includes(key) || key.includes(normalizedName)) {
      return cropImages[key];
    }
  }

  // 4. Try matching individual words from the product name
  const words = normalizedName.split(/\s+/);
  for (const word of words) {
    if (word.length >= 3 && cropImages[word]) {
      return cropImages[word];
    }
  }

  // 5. If no match found, use category fallback
  return categoryImages[category] || defaultFallbackImage;
};

/**
 * Returns a category-level fallback image URL (used when a specific crop image fails to load).
 * This ensures the onError handler doesn't loop back to the same broken URL.
 * @param {string} category - Category of the crop  
 * @returns {string} Category fallback image URL
 */
export const getCategoryFallbackUrl = (category) => {
  return categoryImages[category] || defaultFallbackImage;
};
